//! Obsidian vault resolution and layout: run artefacts live in `<vault>/Pipelines`, durable notes in `<vault>/Knowledge`.
//! Precedence: `--vault`, `AIDP_VAULT` (`off` disables), `~/.aidp/config.json`, then auto-detection; none means legacy layout.

pub use crate::models::vault::{Vault, VaultSource};
use std::path::{Path, PathBuf};

/// Top-level folder inside the vault that holds every pipeline run.
pub const PIPELINES_DIR: &str = "Pipelines";

/// Top-level folder holding the durable per-project knowledge base, a sibling of `Pipelines/`.
/// Two layers, see [`crate::knowledge`]: transverse notes and one note per feature under `Features/`.
pub const KNOWLEDGE_DIR: &str = "Knowledge";

/// Folder inside `<vault>/Pipelines/<repo>/` holding per-repo machine state (in-flight marker, CI ledger).
/// Dot-prefixed so Obsidian and every vault scanner skip it. See [`repo_state_dir`].
pub const STATE_DIR: &str = ".state";

/// Name of the "run underway in this repo" marker inside [`STATE_DIR`].
/// Shared because the CLI writes it and the integrations crate reads it.
pub const RUN_IN_FLIGHT_FILE: &str = "run-in-flight";

/// Name of the CI autopilot's dedup ledger inside [`STATE_DIR`]. See
/// [`migrate_repo_state`].
pub const CI_AUTOPILOT_STATE_FILE: &str = "ci-autopilot.state.json";

/// Every file [`migrate_repo_state`] knows to move out of a repo's legacy
/// `.aidp/` folder and into the vault's per-repo state directory.
const KNOWN_STATE_FILES: &[&str] = &[RUN_IN_FLIGHT_FILE, CI_AUTOPILOT_STATE_FILE];

/// The in-repo folder v7 no longer writes into, but still reads user inputs from.
/// It is also the state directory in legacy (no-vault) mode.
pub const LEGACY_DIR: &str = ".aidp";

/// Prefix marking a note as generated by `aidp`, so it never collides with a stage's declared outputs.
/// Every generated index note is `_<folder-name>.md`.
pub const NOTE_PREFIX: &str = "_";

/// Name of the vault the auto-detector prefers when several are in reach.
const PREFERRED_VAULT_NAME: &str = "aidp";

const VAULT_ENV_VAR: &str = "AIDP_VAULT";
const OBSIDIAN_DIR: &str = ".obsidian";
const GIT_DIR: &str = ".git";
const GIT_CONFIG_FILE: &str = "config";
const GIT_INFO_DIR: &str = "info";
const GIT_EXCLUDE_FILE: &str = "exclude";
const CONFIG_VAULT_KEY: &str = "vault";
const CONFIG_ROOT_KEY: &str = "root";
const CONFIG_FILE_NAME: &str = "config.json";
const WORKSPACE_FALLBACK_SEGMENT: &str = "_workspace";
const INDEX_FALLBACK_NAME: &str = "index";
const EXCLUDE_MARKER: &str =
    "# aidp: vault-backed run artefacts must never land in the repo (LOC-46)";
const DISABLED_VALUES: &[&str] = &["off", "none", "0", "false", "-"];

/// How far up from the workspace the auto-detector looks.
const AUTODETECT_MAX_ANCESTORS: usize = 6;

/// Directory names never considered as a candidate vault.
const AUTODETECT_SKIP: &[&str] = &[
    "node_modules",
    "target",
    "dist",
    "build",
    "bin",
    "obj",
    "vendor",
    ".git",
    ".idea",
    ".vs",
];

impl VaultSource {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Flag => "flag",
            Self::Env => "env:AIDP_VAULT",
            Self::Config => "config:~/.aidp/config.json",
            Self::Autodetect => "autodetect",
        }
    }
}

impl Vault {
    /// `<vault>/Pipelines`.
    pub fn pipelines_dir(&self) -> PathBuf {
        self.root.join(PIPELINES_DIR)
    }

    /// `<vault>/Pipelines/<repo>` — the per-repo equivalent of the legacy
    /// `<workspace>/.aidp/pipelines`.
    pub fn repo_dir(&self, repo: &str) -> PathBuf {
        self.pipelines_dir().join(repo)
    }

    /// `<vault>/Pipelines/<repo>/.state` - see [`STATE_DIR`].
    pub fn repo_state_dir(&self, repo: &str) -> PathBuf {
        self.repo_dir(repo).join(STATE_DIR)
    }

    /// `<vault>/Knowledge`.
    pub fn knowledge_root(&self) -> PathBuf {
        self.root.join(KNOWLEDGE_DIR)
    }

    /// `<vault>/Knowledge/<repo>` — one folder per project.
    pub fn knowledge_dir(&self, repo: &str) -> PathBuf {
        self.knowledge_root().join(repo)
    }

    /// `<vault>/Knowledge/<repo>/Features` — one note per business feature.
    /// See [`crate::knowledge`] for why the base has two layers.
    pub fn knowledge_features_dir(&self, repo: &str) -> PathBuf {
        crate::knowledge::features_dir(&self.knowledge_dir(repo))
    }

    /// Path relative to the vault root, forward-slashed — the form Obsidian
    /// wikilinks use. `None` when `path` is outside the vault.
    pub fn rel(&self, path: &Path) -> Option<String> {
        rel_to(&self.root, path)
    }

    /// Create the vault skeleton (`Pipelines/`). Idempotent.
    pub fn ensure_skeleton(&self) -> std::io::Result<()> {
        std::fs::create_dir_all(self.pipelines_dir())?;
        std::fs::create_dir_all(self.knowledge_root())
    }
}

/// Resolve the vault for `workspace_root`, or `None` for the legacy
/// `.aidp/pipelines/` layout. See the module docs for the precedence chain.
pub fn resolve(explicit: Option<&Path>, workspace_root: &Path) -> Option<Vault> {
    if let Some(p) = explicit {
        return Some(Vault {
            root: normalize(p),
            source: VaultSource::Flag,
            ambiguity: None,
        });
    }
    if let Ok(raw) = std::env::var(VAULT_ENV_VAR) {
        let v = raw.trim();
        if is_disabled(v) {
            return None;
        }
        if !v.is_empty() {
            return Some(Vault {
                root: normalize(Path::new(v)),
                source: VaultSource::Env,
                ambiguity: None,
            });
        }
    }
    if let Some(p) = from_config() {
        return Some(Vault {
            root: normalize(&p),
            source: VaultSource::Config,
            ambiguity: None,
        });
    }
    autodetect(workspace_root)
}

/// `off` / `none` / `0` / `false` / `-` force the legacy layout — the escape
/// hatch for a repo that must keep its artefacts in-tree.
pub fn is_disabled(value: &str) -> bool {
    DISABLED_VALUES.contains(&value.trim().to_ascii_lowercase().as_str())
}

/// Resolve the vault without a workspace: `AIDP_VAULT`, then `~/.aidp/config.json`.
/// Stops before autodetection, and a disabled `AIDP_VAULT` yields `None` without reading the config.
pub fn resolve_global() -> Option<Vault> {
    if let Ok(raw) = std::env::var(VAULT_ENV_VAR) {
        let value = raw.trim();
        if is_disabled(value) {
            return None;
        }
        if !value.is_empty() {
            return Some(Vault {
                root: normalize(Path::new(value)),
                source: VaultSource::Env,
                ambiguity: None,
            });
        }
    }
    from_config().map(|path| Vault {
        root: normalize(&path),
        source: VaultSource::Config,
        ambiguity: None,
    })
}

/// `~/.aidp/config.json`, holding `{"vault": "<path>"}`.
pub fn config_file() -> Option<PathBuf> {
    home_dir().map(|h| h.join(".aidp").join(CONFIG_FILE_NAME))
}

fn from_config() -> Option<PathBuf> {
    let path = config_file()?;
    let text = std::fs::read_to_string(&path).ok()?;
    let v: serde_json::Value = serde_json::from_str(&text).ok()?;
    let raw = match v.get(CONFIG_VAULT_KEY)? {
        serde_json::Value::String(s) => s.clone(),
        obj @ serde_json::Value::Object(_) => obj.get(CONFIG_ROOT_KEY)?.as_str()?.to_string(),
        _ => return None,
    };
    let raw = raw.trim();
    if raw.is_empty() || is_disabled(raw) {
        return None;
    }
    Some(PathBuf::from(expand_home(raw)))
}

/// Search outwards from the workspace for a directory holding `.obsidian/`, testing each ancestor then its children.
/// Nearest level wins; a vault named `AIDP` wins a tie, which is recorded in `ambiguity`.
fn autodetect(workspace_root: &Path) -> Option<Vault> {
    for ancestor in workspace_root.ancestors().take(AUTODETECT_MAX_ANCESTORS) {
        if is_vault(ancestor) {
            return Some(Vault {
                root: normalize(ancestor),
                source: VaultSource::Autodetect,
                ambiguity: None,
            });
        }
        let Ok(entries) = std::fs::read_dir(ancestor) else {
            continue;
        };
        let mut found: Vec<PathBuf> = Vec::new();
        for entry in entries.flatten() {
            let path = entry.path();
            let Some(name) = path.file_name().and_then(|segment| segment.to_str()) else {
                continue;
            };
            if AUTODETECT_SKIP
                .iter()
                .any(|skipped| skipped.eq_ignore_ascii_case(name))
            {
                continue;
            }
            if entry.file_type().map(|kind| kind.is_dir()).unwrap_or(false) && is_vault(&path) {
                found.push(path);
            }
        }
        if found.is_empty() {
            continue;
        }
        found.sort();
        let preferred_index = found
            .iter()
            .position(|candidate| {
                candidate
                    .file_name()
                    .and_then(|segment| segment.to_str())
                    .map(|dir_name| dir_name.eq_ignore_ascii_case(PREFERRED_VAULT_NAME))
                    .unwrap_or(false)
            })
            .unwrap_or(0);
        let ambiguity = (found.len() > 1).then(|| {
            let others: Vec<String> = found
                .iter()
                .enumerate()
                .filter(|(index, _)| *index != preferred_index)
                .map(|(_, candidate)| candidate.display().to_string())
                .collect();
            format!(
                "{} candidate vaults under {}; also saw: {}",
                found.len(),
                ancestor.display(),
                others.join(", ")
            )
        });
        return Some(Vault {
            root: normalize(&found[preferred_index]),
            source: VaultSource::Autodetect,
            ambiguity,
        });
    }
    None
}

fn is_vault(dir: &Path) -> bool {
    dir.join(OBSIDIAN_DIR).is_dir()
}

/// The repo segment of a run's vault path: the git `origin` repository name, else the directory name.
/// Grouping by remote keeps worktrees and second clones of one repo in a single folder.
pub fn repo_segment(workspace_root: &Path) -> String {
    git_repo_name(workspace_root)
        .and_then(|s| sanitize_segment(&s))
        .or_else(|| {
            workspace_root
                .file_name()
                .and_then(|s| s.to_str())
                .and_then(sanitize_segment)
        })
        .unwrap_or_else(|| WORKSPACE_FALLBACK_SEGMENT.to_string())
}

/// Repository name from the `origin` url in `<ws>/.git/config`, read without spawning git.
/// Follows the `gitdir:` pointer when `.git` is a file (worktree or submodule).
fn git_repo_name(workspace_root: &Path) -> Option<String> {
    let git = workspace_root.join(GIT_DIR);
    let config = if git.is_dir() {
        git.join(GIT_CONFIG_FILE)
    } else if git.is_file() {
        let dir = gitdir_of(workspace_root)?;
        if dir.join(GIT_CONFIG_FILE).is_file() {
            dir.join(GIT_CONFIG_FILE)
        } else {
            dir.ancestors()
                .find(|a| a.join(GIT_CONFIG_FILE).is_file())?
                .join(GIT_CONFIG_FILE)
        }
    } else {
        return None;
    };
    let text = std::fs::read_to_string(config).ok()?;
    let mut in_origin = false;
    for line in text.lines() {
        let t = line.trim();
        if t.starts_with('[') {
            in_origin = t
                .replace(char::is_whitespace, "")
                .eq_ignore_ascii_case("[remote\"origin\"]");
            continue;
        }
        if !in_origin {
            continue;
        }
        if let Some((k, v)) = t.split_once('=') {
            if k.trim().eq_ignore_ascii_case("url") {
                return repo_name_from_url(v.trim());
            }
        }
    }
    None
}

/// `git@github.com:org/repo.git` / `https://host/org/repo.git` / a local path → `repo`.
fn repo_name_from_url(url: &str) -> Option<String> {
    let trimmed = url.trim_end_matches('/').trim_end_matches(".git");
    trimmed
        .rsplit(['/', ':', '\\'])
        .find(|s| !s.is_empty())
        .map(|s| s.to_string())
}

/// The directory `<workspace_root>/.git` points at, when `.git` is a *file* -
/// the shape a linked worktree or a submodule has. `None` for a plain checkout.
fn gitdir_of(workspace_root: &Path) -> Option<PathBuf> {
    let text = std::fs::read_to_string(workspace_root.join(GIT_DIR)).ok()?;
    let rest = text.split_once("gitdir:")?.1.trim();
    let dir = PathBuf::from(rest);
    Some(if dir.is_absolute() {
        dir
    } else {
        workspace_root.join(dir)
    })
}

/// The main worktree of the repository containing `p`, resolved from the filesystem without spawning git.
/// For a plain checkout this is `p` itself.
pub fn main_worktree_root(p: &Path) -> PathBuf {
    if p.join(GIT_DIR).is_dir() {
        return p.to_path_buf();
    }
    gitdir_of(p)
        .and_then(|dir| {
            dir.ancestors()
                .find(|a| a.file_name().and_then(|s| s.to_str()) == Some(GIT_DIR))
                .and_then(|a| a.parent())
                .map(Path::to_path_buf)
        })
        .unwrap_or_else(|| p.to_path_buf())
}

/// The repo state directory (legacy `<repo>/.aidp` without a vault) anchored at the main worktree.
/// Pure: never touches the filesystem; call [`migrate_repo_state`] to move stray legacy files.
pub fn repo_state_dir_in(vault: Option<&Vault>, workspace_root: &Path) -> PathBuf {
    let anchor = main_worktree_root(workspace_root);
    match vault {
        Some(v) => v.repo_state_dir(&repo_segment(&anchor)),
        None => anchor.join(LEGACY_DIR),
    }
}

/// A named file under [`repo_state_dir_in`]. Pure - see its own doc for why
/// migration is a separate, explicit step.
pub fn repo_state_path_in(vault: Option<&Vault>, workspace_root: &Path, name: &str) -> PathBuf {
    repo_state_dir_in(vault, workspace_root).join(name)
}

/// Move every [`KNOWN_STATE_FILES`] entry left in `<repo>/.aidp/` into [`repo_state_dir_in`], then prune the folder if empty.
/// Explicit and separate from reading; when both copies exist the vault one wins and the stray is deleted.
pub fn migrate_repo_state(vault: Option<&Vault>, workspace_root: &Path) -> anyhow::Result<()> {
    let anchor = main_worktree_root(workspace_root);
    let legacy_dir = anchor.join(LEGACY_DIR);
    for name in KNOWN_STATE_FILES {
        let legacy = legacy_dir.join(name);
        let target = repo_state_path_in(vault, &anchor, name);
        if legacy != target && legacy.is_file() {
            migrate_state_file(&legacy, &target);
        }
    }
    prune_legacy_dir(&legacy_dir);
    Ok(())
}

fn migrate_state_file(legacy: &Path, target: &Path) {
    if let Some(parent) = target.parent() {
        if std::fs::create_dir_all(parent).is_err() {
            return;
        }
    }
    if !target.exists() {
        if std::fs::rename(legacy, target).is_ok() {
            if let Some(dir) = legacy.parent() {
                prune_legacy_dir(dir);
            }
            return;
        }
        if std::fs::copy(legacy, target).is_err() {
            return;
        }
    }
    let _ = std::fs::remove_file(legacy);
    if let Some(dir) = legacy.parent() {
        prune_legacy_dir(dir);
    }
}

/// Drop `<repo>/.aidp` once empty, since the same folder holds hand-written user input.
/// A failing `remove_dir` on a non-empty folder is the wanted guarantee, so it is ignored.
fn prune_legacy_dir(dir: &Path) {
    if dir.file_name().and_then(|s| s.to_str()) == Some(LEGACY_DIR) {
        let _ = std::fs::remove_dir(dir);
    }
}

/// The generated index note for a directory: `<dir>/_<dir-name>.md`.
pub fn index_note(dir: &Path) -> PathBuf {
    let name = dir
        .file_name()
        .and_then(|s| s.to_str())
        .map(|s| s.to_string())
        .unwrap_or_else(|| INDEX_FALLBACK_NAME.to_string());
    dir.join(format!("{NOTE_PREFIX}{name}.md"))
}

/// Forward-slashed path of `path` relative to `base`, or `None` when it is not under `base`.
/// Falls back to canonicalizing both, which needs them to exist.
pub fn rel_to(base: &Path, path: &Path) -> Option<String> {
    let stripped = match path.strip_prefix(base) {
        Ok(p) => p.to_path_buf(),
        Err(_) => {
            let (cb, cp) = (
                std::fs::canonicalize(base).ok()?,
                std::fs::canonicalize(path).ok()?,
            );
            cp.strip_prefix(&cb).ok()?.to_path_buf()
        }
    };
    Some(stripped.to_string_lossy().replace('\\', "/"))
}

/// Sanitize one raw identifier into a filesystem/branch-safe segment: unsafe characters become `-`.
/// Returns `None` when the value reduces to nothing (empty, `.` or `..`).
pub fn sanitize_segment(s: &str) -> Option<String> {
    let cleaned: String = s
        .trim()
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-') {
                c
            } else {
                '-'
            }
        })
        .collect();
    let trimmed = cleaned.trim_matches(|c| c == '.' || c == '-' || c == '_');
    if trimmed.is_empty() || trimmed == "." || trimmed == ".." {
        None
    } else {
        Some(trimmed.to_string())
    }
}

/// The user's home directory: `USERPROFILE` first, then `HOME`.
/// Returns `None` when neither variable is set.
pub fn home_dir() -> Option<PathBuf> {
    std::env::var_os("USERPROFILE")
        .or_else(|| std::env::var_os("HOME"))
        .map(PathBuf::from)
}

fn expand_home(raw: &str) -> String {
    if let Some(rest) = raw.strip_prefix("~/").or_else(|| raw.strip_prefix("~\\")) {
        if let Some(h) = home_dir() {
            return h.join(rest).to_string_lossy().into_owned();
        }
    }
    raw.to_string()
}

/// Absolutize without requiring the path to exist.
/// Avoids `canonicalize`, which fails on a new vault and adds a `\?\` prefix on Windows.
fn normalize(p: &Path) -> PathBuf {
    if p.is_absolute() {
        return p.to_path_buf();
    }
    std::env::current_dir()
        .map(|c| c.join(p))
        .unwrap_or_else(|_| p.to_path_buf())
}

/// Ensure `.git/info/exclude` carries the vault-path ignore rules; idempotent, returns whether it wrote.
/// Best-effort: an unresolvable `.git` or unwritable file returns `Ok(false)`; linked worktrees write to the main checkout.
pub fn ensure_repo_ignores_vault_paths(workspace_root: &Path) -> std::io::Result<bool> {
    let anchor = main_worktree_root(workspace_root);
    let git_dir = if anchor.join(GIT_DIR).is_dir() {
        anchor.join(GIT_DIR)
    } else if anchor.join(GIT_DIR).is_file() {
        match gitdir_of(&anchor) {
            Some(dir) => dir,
            None => {
                return Ok(false);
            }
        }
    } else {
        return Ok(false);
    };

    let exclude_path = git_dir.join(GIT_INFO_DIR).join(GIT_EXCLUDE_FILE);

    if std::fs::create_dir_all(git_dir.join(GIT_INFO_DIR)).is_err() {
        return Ok(false);
    }

    let ignore_block =
        format!("{EXCLUDE_MARKER}\n{PIPELINES_DIR}/\n{KNOWLEDGE_DIR}/\n{LEGACY_DIR}/pipelines/\n");

    let current_contents = std::fs::read_to_string(&exclude_path).unwrap_or_default();

    if current_contents.contains(EXCLUDE_MARKER) {
        return Ok(false);
    }

    let new_contents = if current_contents.is_empty() {
        ignore_block
    } else {
        let trimmed = current_contents.trim_end();
        format!("{}\n{}", trimmed, ignore_block)
    };

    if std::fs::write(&exclude_path, new_contents).is_err() {
        return Ok(false);
    }

    Ok(true)
}

